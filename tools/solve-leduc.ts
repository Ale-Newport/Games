/**
 * Solves Leduc poker with CFR+ and writes the equilibrium table used by the Nash opponent:
 * `npx tsx tools/solve-leduc.ts [iterations]` → src/games/leduc-poker/strategy.ts.
 */
import { writeFileSync } from 'node:fs';
import { exploitability, solveCfr, strategyValue } from '../src/ai/agents/cfr';
import { LEDUC_GAME } from '../src/games/leduc-poker/cfr-game';

const iterations = Number(process.argv[2] ?? 3000);
const started = Date.now();
const strategy = solveCfr(LEDUC_GAME, iterations);
const policy = (h: Parameters<typeof LEDUC_GAME.infoKey>[0]) => strategy[LEDUC_GAME.infoKey(h)]!;
const value = strategyValue(LEDUC_GAME, policy, policy);
const exploit = exploitability(LEDUC_GAME, policy);
const rounded = Object.fromEntries(
  Object.entries(strategy)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([k, v]) => [k, v.map((x) => Math.round(x * 10000) / 10000)]),
);
const header = `/**
 * Leduc poker Nash equilibrium: CFR+ (${iterations} iterations, generated by tools/solve-leduc.ts).
 * Key: own rank (0 jack, 1 queen, 2 king), public rank or "-", then the betting of each round.
 * Value for the first player ${value.toFixed(4)} chips a hand; exploitability ${exploit.toFixed(4)}.
 */
`;
writeFileSync(
  'src/games/leduc-poker/strategy.ts',
  `${header}export const LEDUC_NASH: Record<string, number[]> = ${JSON.stringify(rounded, null, 2)};\n`,
);
console.log(
  `${Object.keys(strategy).length} information sets, value ${value.toFixed(4)}, exploitability ${exploit.toFixed(5)}, ${Date.now() - started} ms`,
);
