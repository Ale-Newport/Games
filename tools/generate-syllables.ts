/**
 * Builds the #217 Syllable Bomb word list and prompts:
 *   src/games/syllable-bomb/words.txt   lowercase words (3–15 letters): Webster's Second
 *                                       International (1934, public domain, /usr/share/dict/web2)
 *                                       plus the shared 30,000-word modern vocabulary
 *   src/games/syllable-bomb/prompts.ts  2–3 letter prompts with how many words contain them
 * Run: npx tsx tools/generate-syllables.ts
 */
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../', import.meta.url);
const web2 = readFileSync('/usr/share/dict/web2', 'utf8').split('\n');
const modern = readFileSync(new URL('src/games/shared/semantic/words.txt', root), 'utf8').split(
  '\n',
);
const words = [...new Set([...web2, ...modern].filter((w) => /^[a-z]{3,15}$/.test(w)))].sort();
writeFileSync(new URL('src/games/syllable-bomb/words.txt', root), words.join('\n') + '\n');

const counts = new Map<string, number>();
for (const w of words) {
  const seen = new Set<string>();
  for (let n = 2; n <= 3; n++) for (let i = 0; i + n <= w.length; i++) seen.add(w.slice(i, i + n));
  for (const s of seen) counts.set(s, (counts.get(s) ?? 0) + 1);
}
// Prompts must also be common in everyday words, so check the modern list too.
const modernSet = modern.filter((w) => /^[a-z]{3,}$/.test(w));
const modernCount = (s: string) => modernSet.filter((w) => w.includes(s)).length;
const tiers = {
  easy: [] as [string, number][],
  medium: [] as [string, number][],
  hard: [] as [string, number][],
};
for (const [s, c] of counts) {
  if (!/^[a-z]+$/.test(s)) continue;
  const m = modernCount(s);
  if (c >= 2500 && m >= 300) tiers.easy.push([s, c]);
  else if (c >= 600 && m >= 60) tiers.medium.push([s, c]);
  else if (c >= 150 && m >= 12) tiers.hard.push([s, c]);
}
for (const k of Object.keys(tiers) as (keyof typeof tiers)[]) tiers[k].sort((a, b) => b[1] - a[1]);
writeFileSync(
  new URL('src/games/syllable-bomb/prompts.ts', root),
  `/** GENERATED by tools/generate-syllables.ts. Prompt → number of dictionary words containing it. */\n` +
    `export const PROMPTS: Record<'easy' | 'medium' | 'hard', [string, number][]> = ${JSON.stringify(tiers)};\n`,
);
console.log(
  `words ${words.length}; prompts easy ${tiers.easy.length} medium ${tiers.medium.length} hard ${tiers.hard.length}`,
);
